    async fn write_note(root: &Path, rel: &str, body: &str) -> PathBuf {
        let path = root.join(rel);
        tokio::fs::create_dir_all(path.parent().unwrap())
            .await
            .unwrap();
        tokio::fs::write(&path, body).await.unwrap();
        path
    }

