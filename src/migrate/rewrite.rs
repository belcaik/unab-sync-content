//! Frontmatter and local links for markdown u_crawler generated.
//!
//! [`rewrite_file`] is the only writer. It copies the original bytes to
//! `.u_crawler/backup/<ts>/` and then replaces the note through
//! [`fsutil::atomic_write`]: a new file in the same directory, renamed over
//! the old name. The previous inode stays with any other hardlink (`cp -al`),
//! so the library the clone was made from does not change.
//!
//! The backup is a byte copy, not another hardlink. An in-place edit of the
//! backup must not reach the source inode.
//!
//! A path [`generated_kind`] does not recognize is not opened for writing.
//! Symlinks are refused, so a rewrite cannot follow a link out of the library.

use crate::frontmatter::{self, DocKind, Frontmatter};
use crate::fsutil;
use crate::layout::{ANNOUNCEMENTS_DIR, ASSIGNMENTS_DIR, META_DIR, MODULES_DIR, RECORDINGS_DIR};
use crate::links::{self, LinkMap, LinkStats};
use std::io;
use std::path::{Component, Path, PathBuf};
use thiserror::Error;

/// Directory name of modules in a v1 library. `syncer` still writes this.
const V1_MODULES_DIR: &str = "Modules";
/// Directory name of announcements in a v1 library. `announcements` still writes this.
const V1_ANNOUNCEMENTS_DIR: &str = "announcements";

/// One note to rewrite. Paths in `links` are relative to `root`, like the note.
pub struct Rewrite<'a> {
    /// Library root. The backup is `<root>/.u_crawler/backup/<backup_ts>/`.
    pub root: &'a Path,
    /// Note to rewrite, absolute or relative to `root`.
    pub path: &'a Path,
    /// Properties to write. Replaces our keys; does not touch any other key.
    /// `None` leaves the frontmatter exactly as it is (links only).
    pub frontmatter: Option<&'a Frontmatter>,
    /// Where each Canvas resource is, relative to `root`.
    pub links: &'a LinkMap,
    /// Single path segment naming this backup batch. `[A-Za-z0-9._-]` only.
    pub backup_ts: &'a str,
}

/// What [`rewrite_file`] did.
#[derive(Debug, PartialEq, Eq)]
pub enum RewriteOutcome {
    /// The note already had this frontmatter and these links. Nothing was written.
    Unchanged,
    /// The previous bytes were copied to `backup`, then the note was replaced.
    Rewritten {
        /// Copy of the bytes from before this call.
        backup: PathBuf,
        /// Links this call pointed at a local copy.
        local: usize,
    },
}

/// Why a note was left untouched.
#[derive(Debug, Error)]
pub enum RewriteError {
    /// `backup_ts` is empty, `.`, `..`, or not a single safe path segment.
    #[error("backup timestamp must be one path segment of [A-Za-z0-9._-]")]
    BadTimestamp,
    /// `path` is not inside `root` after resolving `.` and `..`.
    #[error("path escapes the library root: {0}")]
    EscapesRoot(PathBuf),
    /// The path is not a markdown file this program generated.
    #[error("not a markdown file generated by u_crawler: {0}")]
    NotGenerated(PathBuf),
    /// A symlink would have to be followed or replaced. Neither is safe.
    #[error("refusing to follow or replace a symlink: {0}")]
    Symlink(PathBuf),
    /// The path exists and is not a regular file.
    #[error("not a regular file: {0}")]
    NotAFile(PathBuf),
    /// The note is not UTF-8, so it is not treated as markdown.
    #[error("markdown is not valid UTF-8: {0}")]
    NotUtf8(PathBuf),
    /// A backup for this timestamp exists and the note is neither that backup
    /// nor the bytes we would write. Both files are left as they are.
    #[error("file changed since the backup at {backup} was taken")]
    ChangedSinceBackup {
        /// The backup that does not match the note anymore.
        backup: PathBuf,
    },
    /// `<path>.part` already exists and is not a symlink. `atomic_write` would
    /// replace it. The scratch file and the note are left as they are. A
    /// symlink scratch file is [`RewriteError::Symlink`] instead.
    #[error("refusing to replace an existing scratch file: {0}")]
    PartExists(PathBuf),
    /// A filesystem call failed. The note was not replaced.
    #[error(transparent)]
    Io(#[from] io::Error),
}

/// Kind of generated note `rel` is, relative to the library root.
///
/// Recognizes v1 (`Modules/<id>_<name>/NN-….md`, `announcements/…_<id>.md`)
/// and v2 (`modulos/`, `tareas/`, `anuncios/`, `grabaciones/` from
/// [`crate::layout`]). `README.md`, notes at the course root, `.git`,
/// `.obsidian` and `.u_crawler` are not generated notes.
pub fn generated_kind(rel: &Path) -> Option<DocKind> {
    let comps = utf8_components(rel)?;
    if comps.iter().any(|component| is_foreign_meta(component)) {
        return None;
    }
    for (index, dir) in comps.iter().enumerate() {
        if let Some(kind) = kind_under(dir, &comps[index + 1..]) {
            return Some(kind);
        }
    }
    None
}

/// Frontmatter plus local links, without touching the filesystem.
///
/// Link targets in the body are rewritten ([`relink`]). The `url` property
/// is not: it is the note's own Canvas URL and is written from `fm`. A
/// leading `---` that is not a property block is body, so a Canvas link
/// between two horizontal rules is rewritten too.
pub fn apply(markdown: &str, fm: &Frontmatter, md_path: &Path, links: &LinkMap) -> String {
    frontmatter::upsert(&relink(markdown, md_path, links).0, fm)
}

/// The note with the Canvas links of its body pointing at the local copies
/// `links` knows ([`links::rewrite_canvas_links`]). The frontmatter, BOM
/// included, is left byte for byte.
pub fn relink(markdown: &str, md_path: &Path, links: &LinkMap) -> (String, LinkStats) {
    let (bom, markdown) = frontmatter::strip_bom(markdown);
    let (rewritten, stats) = match frontmatter::split_frontmatter(markdown) {
        Some((yaml, body)) => {
            let (body, stats) = links::rewrite_canvas_links(body, md_path, links);
            (frontmatter::join_frontmatter(yaml, &body), stats)
        }
        None => links::rewrite_canvas_links(markdown, md_path, links),
    };
    (format!("{bom}{rewritten}"), stats)
}

/// Back up `job.path` and rewrite it, or leave it alone.
///
/// # Errors
///
/// [`RewriteError`] when the timestamp is unsafe, the path leaves the library,
/// the note was not generated by u_crawler, a symlink is in the way, a regular
/// `.part` scratch file is already beside the note or the backup, the bytes
/// are not UTF-8, the note changed after a backup was taken, or a filesystem
/// call fails. In every error case the note's bytes are unchanged.
pub async fn rewrite_file(job: &Rewrite<'_>) -> Result<RewriteOutcome, RewriteError> {
    if !valid_timestamp(job.backup_ts) {
        return Err(RewriteError::BadTimestamp);
    }
    let root = normalize(job.root);
    let rel = relative_to_root(&root, job.path)?;
    if generated_kind(&rel).is_none() {
        return Err(RewriteError::NotGenerated(rel));
    }
    let full = root.join(&rel);
    ensure_no_symlink(&root, &rel).await?;
    let meta = tokio::fs::symlink_metadata(&full).await?;
    if !meta.is_file() {
        return Err(RewriteError::NotAFile(full));
    }
    let bytes = tokio::fs::read(&full).await?;
    let text = String::from_utf8(bytes).map_err(|_| RewriteError::NotUtf8(rel.clone()))?;
    let (relinked, stats) = relink(&text, &rel, job.links);
    if !stats.ambiguous.is_empty() {
        tracing::info!(
            path = %rel.display(),
            file_ids = ?stats.ambiguous,
            "Canvas file links left remote: more than one local file could be each"
        );
    }
    let new_text = match job.frontmatter {
        Some(fm) => frontmatter::upsert(&relinked, fm),
        None => relinked,
    };
    if new_text == text {
        return Ok(RewriteOutcome::Unchanged);
    }
    let backup = backup_then_write(&root, &rel, &text, &new_text, job.backup_ts).await?;
    Ok(RewriteOutcome::Rewritten {
        backup,
        local: stats.local,
    })
}

/// Back up and rewrite a course's `.u_crawler/state.json`, as
/// [`rewrite_file`] does a note: what the migration learned from Canvas
/// (paths) is kept for the next offline run, and `--undo` puts the bytes
/// back with the notes. `rel` must be `<course>/.u_crawler/state.json`.
///
/// # Errors
///
/// As [`rewrite_file`]; [`RewriteError::NotGenerated`] for any other path.
pub async fn rewrite_state(
    root: &Path,
    rel: &Path,
    new_text: &str,
    backup_ts: &str,
) -> Result<RewriteOutcome, RewriteError> {
    if !valid_timestamp(backup_ts) {
        return Err(RewriteError::BadTimestamp);
    }
    let root = normalize(root);
    let rel = relative_to_root(&root, rel)?;
    let is_state = matches!(
        utf8_components(&rel).as_deref(),
        Some([course, META_DIR, "state.json"]) if !is_foreign_meta(course) && *course != ".."
    );
    if !is_state {
        return Err(RewriteError::NotGenerated(rel));
    }
    let full = root.join(&rel);
    ensure_no_symlink(&root, &rel).await?;
    let meta = tokio::fs::symlink_metadata(&full).await?;
    if !meta.is_file() {
        return Err(RewriteError::NotAFile(full));
    }
    let bytes = tokio::fs::read(&full).await?;
    let text = String::from_utf8(bytes).map_err(|_| RewriteError::NotUtf8(rel.clone()))?;
    if new_text == text {
        return Ok(RewriteOutcome::Unchanged);
    }
    let backup = backup_then_write(&root, &rel, &text, new_text, backup_ts).await?;
    Ok(RewriteOutcome::Rewritten { backup, local: 0 })
}

/// Copy `text` (the current bytes of `<root>/<rel>`) to the backup of
/// `backup_ts`, unless that backup already holds them, then write
/// `new_text`. Returns the backup's path.
async fn backup_then_write(
    root: &Path,
    rel: &Path,
    text: &str,
    new_text: &str,
    backup_ts: &str,
) -> Result<PathBuf, RewriteError> {
    let full = root.join(rel);
    let backup = root.join(META_DIR).join("backup").join(backup_ts).join(rel);
    if symlink_at(&backup).await? {
        return Err(RewriteError::Symlink(backup));
    }
    // `atomic_write` truncates `path.with_extension("part")`. Refuse when that
    // name is already taken so a user's file, or a crash leftover, is not
    // replaced. Checked after the diverge test: that error still means the
    // note and the backup disagree, and neither is written.
    let creating_backup = match tokio::fs::read(&backup).await {
        Ok(previous) if previous == text.as_bytes() => false,
        Ok(_) => return Err(RewriteError::ChangedSinceBackup { backup }),
        Err(err) if err.kind() == io::ErrorKind::NotFound => true,
        Err(err) => return Err(err.into()),
    };
    ensure_scratch_free(&full).await?;
    if creating_backup {
        ensure_scratch_free(&backup).await?;
        write_bytes(&backup, text.as_bytes()).await?;
    }
    write_bytes(&full, new_text.as_bytes()).await?;
    Ok(backup)
}

fn valid_timestamp(ts: &str) -> bool {
    !ts.is_empty()
        && ts != "."
        && ts != ".."
        && ts
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '.' || c == '_' || c == '-')
}

fn relative_to_root(root: &Path, path: &Path) -> Result<PathBuf, RewriteError> {
    if root.as_os_str().is_empty() {
        return Err(RewriteError::EscapesRoot(path.to_path_buf()));
    }
    let full = if path.is_absolute() {
        normalize(path)
    } else {
        normalize(&root.join(path))
    };
    full.strip_prefix(root)
        .map(Path::to_path_buf)
        .map_err(|_| RewriteError::EscapesRoot(path.to_path_buf()))
}

fn normalize(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for component in path.components() {
        match component {
            Component::CurDir => {}
            Component::ParentDir => match out.components().next_back() {
                Some(Component::Normal(_)) => {
                    out.pop();
                }
                Some(Component::ParentDir) | None => out.push(".."),
                _ => {}
            },
            other => out.push(other.as_os_str()),
        }
    }
    out
}

async fn ensure_no_symlink(root: &Path, rel: &Path) -> Result<(), RewriteError> {
    if symlink_at(root).await? {
        return Err(RewriteError::Symlink(root.to_path_buf()));
    }
    let mut current = root.to_path_buf();
    for component in rel.components() {
        current.push(component);
        if symlink_at(&current).await? {
            return Err(RewriteError::Symlink(current));
        }
    }
    Ok(())
}

async fn symlink_at(path: &Path) -> io::Result<bool> {
    match tokio::fs::symlink_metadata(path).await {
        Ok(meta) => Ok(meta.file_type().is_symlink()),
        Err(err) if err.kind() == io::ErrorKind::NotFound => Ok(false),
        Err(err) => Err(err),
    }
}

async fn ensure_scratch_free(path: &Path) -> Result<(), RewriteError> {
    let tmp = path.with_extension("part");
    match tokio::fs::symlink_metadata(&tmp).await {
        Ok(meta) if meta.file_type().is_symlink() => Err(RewriteError::Symlink(tmp)),
        Ok(_) => Err(RewriteError::PartExists(tmp)),
        Err(err) if err.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(err) => Err(err.into()),
    }
}

async fn write_bytes(path: &Path, bytes: &[u8]) -> Result<(), RewriteError> {
    ensure_scratch_free(path).await?;
    fsutil::atomic_write(path, bytes).await?;
    Ok(())
}

fn utf8_components(path: &Path) -> Option<Vec<&str>> {
    let mut out = Vec::new();
    for component in path.components() {
        match component {
            Component::Normal(part) => out.push(part.to_str()?),
            _ => return None,
        }
    }
    Some(out)
}

fn is_foreign_meta(component: &str) -> bool {
    component == ".git" || component == ".obsidian" || component == META_DIR
}

fn kind_under(dir: &str, rest: &[&str]) -> Option<DocKind> {
    match dir {
        V1_MODULES_DIR => v1_module(rest),
        V1_ANNOUNCEMENTS_DIR => v1_announcement(rest),
        MODULES_DIR => v2_page(rest),
        ASSIGNMENTS_DIR => v2_kebab_file(rest, DocKind::Assignment),
        ANNOUNCEMENTS_DIR => v2_dated(rest, DocKind::Announcement),
        RECORDINGS_DIR => v2_dated(rest, DocKind::Recording),
        _ => None,
    }
}

fn v1_module(rest: &[&str]) -> Option<DocKind> {
    let [dir, file] = *rest else {
        return None;
    };
    if !is_v1_module_dir(dir) {
        return None;
    }
    v1_module_file(file)
}

fn is_v1_module_dir(dir: &str) -> bool {
    let Some((id, name)) = dir.split_once('_') else {
        return false;
    };
    !id.is_empty() && id.chars().all(|c| c.is_ascii_digit()) && !name.is_empty()
}

fn v1_module_file(file: &str) -> Option<DocKind> {
    let stem = file.strip_suffix(".md")?;
    let (pos, rest) = stem.split_once('-')?;
    if pos.len() < 2 || !pos.chars().all(|c| c.is_ascii_digit()) || rest.is_empty() {
        return None;
    }
    match rest.strip_prefix("ASSIGN-") {
        Some(title) if !title.is_empty() => Some(DocKind::Assignment),
        Some(_) => None,
        None => Some(DocKind::Page),
    }
}

fn v1_announcement(rest: &[&str]) -> Option<DocKind> {
    let [file] = *rest else {
        return None;
    };
    let stem = file.strip_suffix(".md")?;
    let (head, id) = stem.rsplit_once('_')?;
    if id.is_empty() || !id.chars().all(|c| c.is_ascii_digit()) || head.is_empty() {
        return None;
    }
    let slug = strip_v1_date(head).unwrap_or(head);
    if is_v1_slug(slug) {
        Some(DocKind::Announcement)
    } else {
        None
    }
}

fn strip_v1_date(head: &str) -> Option<&str> {
    let (date, slug) = head.split_once('_')?;
    if is_iso_date(date) {
        Some(slug)
    } else {
        None
    }
}

fn is_v1_slug(slug: &str) -> bool {
    !slug.is_empty() && slug.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn v2_page(rest: &[&str]) -> Option<DocKind> {
    let [module, file] = *rest else {
        return None;
    };
    let stem = file.strip_suffix(".md")?;
    if is_pos_slug(module) && is_pos_slug(stem) {
        Some(DocKind::Page)
    } else {
        None
    }
}

fn v2_kebab_file(rest: &[&str], kind: DocKind) -> Option<DocKind> {
    let [file] = *rest else {
        return None;
    };
    let stem = file.strip_suffix(".md")?;
    if is_kebab(stem) {
        Some(kind)
    } else {
        None
    }
}

fn v2_dated(rest: &[&str], kind: DocKind) -> Option<DocKind> {
    let [file] = *rest else {
        return None;
    };
    let stem = file.strip_suffix(".md")?;
    let (date, slug) = stem.split_once('_')?;
    if is_iso_date(date) && is_kebab(slug) {
        Some(kind)
    } else {
        None
    }
}

fn is_pos_slug(value: &str) -> bool {
    let Some((pos, slug)) = value.split_once('-') else {
        return false;
    };
    pos.len() >= 2 && pos.chars().all(|c| c.is_ascii_digit()) && is_kebab(slug)
}

fn is_kebab(value: &str) -> bool {
    !value.is_empty()
        && !value.starts_with('-')
        && !value.ends_with('-')
        && !value.contains("--")
        && value
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
}

fn is_iso_date(value: &str) -> bool {
    let mut parts = value.split('-');
    let (Some(year), Some(month), Some(day)) = (parts.next(), parts.next(), parts.next()) else {
        return false;
    };
    if parts.next().is_some() {
        return false;
    }
    year.len() == 4
        && year.chars().all(|c| c.is_ascii_digit())
        && in_range(month, 1, 12)
        && in_range(day, 1, 31)
}

fn in_range(value: &str, min: u32, max: u32) -> bool {
    value.len() == 2
        && value.chars().all(|c| c.is_ascii_digit())
        && value
            .parse::<u32>()
            .is_ok_and(|number| (min..=max).contains(&number))
}

