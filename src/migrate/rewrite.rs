        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path();
        let path = write_note(root, rel_v1(), ORIGINAL).await;
        let fm = page_fm();
        let files = files_for("course/Modules/12_Intro/adjuntos/guia.pdf");
        let outcome = rewrite_file(&Rewrite {
            root,
            path: &path,
            frontmatter: Some(&fm),
            links: &files,
            backup_ts: "20261025T120000Z",
        })
        .await
        .unwrap();
        let backup = root
            .join(".u_crawler/backup/20261025T120000Z")
            .join(rel_v1());
        assert_eq!(
            outcome,
            RewriteOutcome::Rewritten {
                backup: backup.clone(),
                local: 1,
            }
        );
        assert_eq!(std::fs::read(&backup).unwrap(), ORIGINAL.as_bytes());
        let text = std::fs::read_to_string(&path).unwrap();
